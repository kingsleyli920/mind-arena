// 提示词装配。
//
// 分两段，边界是刻意的：
//   system —— 规则摘要 + 交代。**逐字节稳定**，不含席位名、不含年份、
//              不含 seed。稳定才命中前缀缓存；一局 16 季重复发同一份
//              3.8k token，不缓存是纯浪费。
//   user   —— 本季观测的 JSON。每季全变。
import { toRulesDigest } from "../../game/content/schema.ts";
import type { Observation } from "../../game/engine/observe.ts";

export const PROMPT_VERSION = "1.0.0";

/** 静态前缀。同一内容包下逐字节相同，不随席位、季数、seed 变化 */
export function renderSystem(pack: unknown): string {
  return [
    "你是汉末群雄之一的谋主。每季从引擎给出的候选里挑几条令下达，十六季后按战果定档。",
    "",
    "## 怎么下令",
    "- 只能从 candidates 里按 key 选，不得自造动作、不得改参数。引擎已把可行的选项筛好了。",
    "- 一季可下多条，总耗令不超过 budget.ap。picks 的顺序即优先级：令数不够时先保前面的。",
    "- 候选逐条合法，但**一起下不一定合法**：同一郡每季至多 2 令，刺探 3 次、任命 5 次。",
    "  越界的会被逐条丢弃，不作废整回合——但那是白费的机会。",
    "",
    "## 怎么看候选",
    "- 征伐候选带 forecast：缺口数对可防守数，破城的判据是**缺口严格大于可防守**。",
    "  verdict 为「未知」多半是因为没探明：未探时敌方城防（20–100）与守将加成（0–2）都不明，",
    "  区间必然偏宽。刺探是免费的，它把区间收窄。",
    "- 敌方守军是观测值不是真值：未探只知档位区间，已探是带误差的点估计。",
    "- forecast 只答「打不打得赢」。**打赢了值什么**写在标签末尾：目标所属州、",
    "  「再取 N 即控」、「·州治」、「·敌治所」、「取下即升某档」。",
    "  这两件事经常不指向同一个目标——最好打的那个未必是让你升档的那个。",
    "",
    "## 怎么算赢",
    "- 档位按**相对开局的增量**判，不是绝对疆域。守成不得分。",
    "- 多控一州或多据一州治 → 乙；多控两州 → 甲；郡数高于开局且至少一郡夺自他方 → 丙。",
    "- 控制一州 = 拥有该州过半郡国。brief 里逐州写了还差几郡。",
    "- 只捡无主之地不算进攻，拿不到丙档。",
    "- 升档是阶梯不是斜坡：第五个散郡值 0 分，凑成半州的那一个郡值一整档。",
    "- 治所失守则全境补给断绝，是全图杠杆最高的一击——对手的治所与自己的都算。",
    "",
    "## 输出",
    '只回 JSON：{"picks": ["候选key", ...], "reason": "一句话意图"}',
    "",
    "## 规则细则",
    toRulesDigest(pack as never),
  ].join("\n");
}

/** 本季的观测。JSON 直发，不另做散文——散文会引入措辞变量，评测不可比 */
export function renderUser(o: Observation): string {
  return JSON.stringify(o);
}
