    "不是格言：",
    "- **别掏空老巢。** 邻敌最多带走自己八成守军，而破开两档可防守要兵力比 2.0——",
    "  所以出兵后余兵低于最强邻敌守军的 **0.4 倍**，这一郡就是一击可破。",
    "  候选标签写着「城中余 N 人」，拿它对一下邻郡的守军再决定倾国还是出偏师。",
