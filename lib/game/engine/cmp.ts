/**
 * 字符串的确定性比较。
 *
 * **不要用 String.prototype.localeCompare。** 不传 locale 时它取宿主的默认地区，
 * 于是同一份代码在不同机器上给出不同的全序，而引擎的每一处排序都是结算的输入：
 * canonicalOrder 的命令归一、campaigns 的先后、sieges 的 seq、候选表的排位。
 *
 * 这不是理论风险，是实测：105 个郡国 id 在 en 下与码点序完全一致，在 zh / zh-CN
 * 下**全部**换位（首位从「上党郡」变成「安定郡」）。同种子、同机器人逻辑，只把
 * 宿主地区从 en 换成 zh，跑 12 季之后 135 个状态字段里 119 个分岔——河内郡守军
 * 一边 7378、一边 407。R33 说「同种子 + 同命令 → 逐位一致的重放」，而它实际只在
 * 同一地区内成立；评测跑在 Node(en-US)，用户的浏览器是 zh-CN，两边不是同一局游戏。
 *
 * 也不要换成 Intl.Collator("en")：那把结果绑到宿主的 ICU 版本上，同样不可移植。
 * 码点比较没有任何环境依赖，且实测与本仓库此前的 en-US 行为逐位相同——
 * 所以这次替换不需要重录任何基线。
 */
export const cmp = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);
