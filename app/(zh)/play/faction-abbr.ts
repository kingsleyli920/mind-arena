/**
 * 势力的一字缩写。军团那枚小圆点上写它。
 *
 * 为什么不写「留／行／围」：那是**状态**，而状态已经由圆环表达了
 *（虚环＝在途、实心＝驻守、城下另有围城旗）。图上真正缺的是
 * **「这是谁的兵」**——三十一家，颜色肉眼分不清，而一个字就够。
 *
 * 取字的规矩：
 *   姓会撞（袁绍/袁术、张济/张杨、公孙瓒/公孙度、刘备/刘表/刘璋），
 *   所以人名取**名的末字**：绍、术、济、杨、瓒、度、备、表、璋。
 *   非人名（白波军、鲜卑诸部、乌桓、羌胡这类）取首字。
 *   括号里的从属、顿号后的并列一律先剥掉：「吕布（张邈、陈宫）」→ 布。
 *
 * 单独成文件是为了让测试读得到（PlayClient.tsx 带 JSX，测试里 import 不进来）——
 * 与 panels.ts、grade-gap.ts 同一个理由。一条测试钉住「三十一家互不相同」：
 * 撞了就等于图上两支不同势力的兵长得一模一样。
 */
export function factionAbbr(name: string): string {
  const head = name.split(/[（(]/)[0].split("、")[0].trim();
  if (!head) return "?";
  if (/[军部胡族]$/.test(head) || head.length > 3) return head[0];
  return head[head.length - 1];
}
