// ── 口径 ────────────────────────────────────────────────────────────────────
// 主体来源：《三国志》（陈寿撰、裴松之注）有传及附传人物；
//           《后汉书》（范晔）列传中的汉末人物；
//           少量取《华阳国志》（常璩）、《晋书》（唐修，用于三国末年入晋者）。
//           以上均为公有领域古籍。
// 演义人物：《三国演义》独有的虚构人物单独标 fictional: true，certainty: "romance"，
//           与史实人物不混淆。史书仅存姓名而演义大加发挥者（如管亥、蔡阳）
//           仍算史实人物，fictional: false，但 certainty 记为 sparse。
// 数值纪律：本文件不含任何五维/战法数值。人名、字、籍贯、生卒、官职、事迹属史实，
//           可自由使用；商业游戏（光荣《三国志》系列等）的具体数值表、能力表、
//           美术资源一概不抄录、不参考。prominence 是本项目自定的史料显著度分级，
//           依据是人物在《三国志》《后汉书》中的立传规格与记载篇幅，不是战力评价。
//
// ── 字段 ────────────────────────────────────────────────────────────────────
// id             拼音（无声调、无空格）。同名同姓者加籍贯或世次后缀，如 sunhao_wu。
// name           姓名（汉字）
// courtesyName   字；史无明文者 null
// birthYear      公元生年；不详 null（负数表示公元前，本表未用到）
// deathYear      公元卒年；不详 null
// origin         籍贯原文，尽量到县
// commandery     对应 commanderies.json 的郡国 id（东汉顺帝时建置）。
//                后世新置之郡（南安、天水改名、巴西、义阳、阳平、襄阳等）一律回溯到
//                《续汉书·郡国志》的母郡，差异写在 historicalNote 或此处注释里。
//                籍贯不详者 null。
// affiliation194 兴平元年（194）岁末的归属，对应 scenario-194.json 的 factionId。
//                在野、未仕、已故、尚未出生者一律 null。
//                注意：这是"本年此人在为谁做事"，不是"此人一生的主君"。
//                关羽张飞此年随刘备在徐州，故记 liubei 而非蜀汉；
//                张辽此年在吕布麾下，故记 lubu 而非 caocao。
// roles          标签，取自 ROLES 白名单
// sources        史料出处
// historicalNote 一两句生平要点；194 年的处境若与后世主君不同，在此说明
// fictional      是否演义虚构
// certainty      attested 史料详实（有传或附传，事迹清楚）
//                sparse   记载简略（散见数条，或仅具官职姓名）
//                romance  主要靠演义补充（含全部 fictional，也含史书一名而演义大写者）
// prominence     1 顶级（有独立传且影响一代格局）
//                2 重要（有传或详附传，一方之柱石）
//                3 一般（附传或散见，事迹可考）
//                4 仅见姓名（史书一两笔带过，或演义配角）
//                虚构人物无史料可依，其 prominence 按演义中的戏份定级，
//                与史实人物的分级口径不同，取数值时须一并看 fictional 字段。
//
// 反复运行结果一致：无网络、无随机、无时间依赖。
