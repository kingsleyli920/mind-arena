const commanderies = JSON.parse(fs.readFileSync(COMMANDERIES, "utf8"));
const scenario = JSON.parse(fs.readFileSync(SCENARIO, "utf8"));
const COMMANDERY_IDS = new Set(commanderies.map((c) => c.id));
const FACTION_IDS = new Set(scenario.factions.map((f) => f.id));
const FACTION_NAME = new Map(scenario.factions.map((f) => [f.id, f.name]));

const CERTAINTY = new Set(["attested", "sparse", "romance"]);
const errors = [];
const warnings = [];
const blank = (v) => v === "" || v === undefined ? null : v;

const officers = [];
const seenId = new Set();
let normalizedDead = 0;
let normalizedUnborn = 0;

for (const row of ROWS) {
  const [
    affiliationRaw, id, name, courtesyRaw, birthYear, deathYear,
    originRaw, commanderyRaw, rolesRaw, prominence, certainty, sourcesRaw, note,
  ] = row;

  if (typeof id !== "string" || !/^[a-z][a-z0-9_]*$/.test(id)) {
    errors.push(`非法 id：${JSON.stringify(id)}（${name}）`);
    continue;
  }
  if (seenId.has(id)) { errors.push(`id 重复：${id}（${name}）`); continue; }
  seenId.add(id);

  const roles = String(rolesRaw).split("|").filter(Boolean);
  for (const r of roles) if (!ROLES.has(r)) errors.push(`${id} ${name}：未知 role「${r}」`);
  if (!roles.length) errors.push(`${id} ${name}：roles 为空`);

  const sources = String(sourcesRaw).split("|").filter(Boolean);
  if (!sources.length) errors.push(`${id} ${name}：sources 为空`);

  if (!CERTAINTY.has(certainty)) errors.push(`${id} ${name}：非法 certainty「${certainty}」`);
  if (![1, 2, 3, 4].includes(prominence)) errors.push(`${id} ${name}：非法 prominence「${prominence}」`);
  if (typeof note !== "string" || note.length < 10) errors.push(`${id} ${name}：historicalNote 过短`);

  const commandery = blank(commanderyRaw);
  if (commandery !== null && !COMMANDERY_IDS.has(commandery)) {
    errors.push(`${id} ${name}：郡国「${commandery}」不在 commanderies.json 中`);
  }

  const fictional = FICTIONAL.has(id);
  if (fictional && certainty !== "romance") errors.push(`${id} ${name}：虚构人物 certainty 必须为 romance`);
  if (!fictional && certainty === "romance") errors.push(`${id} ${name}：certainty=romance 但未登记于 FICTIONAL`);
  if (fictional && sources.some((s) => s.startsWith("三国志") || s.startsWith("后汉书"))) {
    errors.push(`${id} ${name}：虚构人物不得以正史为出处`);
  }

  if (birthYear !== null && deathYear !== null && birthYear >= deathYear) {
    errors.push(`${id} ${name}：生年 ${birthYear} 不早于卒年 ${deathYear}`);
  }

  // 归一化：194 年岁末已不在人世、或尚未出生者，本年不可能有归属。
  // 源数据中他们仍编在「生前所属/日后所属」的段落里，便于按阵营查阅，此处统一置 null。
  let affiliation194 = affiliationRaw;
  if (deathYear !== null && deathYear < 194) {
    if (affiliation194 !== null) normalizedDead++;
    affiliation194 = null;
  } else if (birthYear !== null && birthYear > 194) {
    if (affiliation194 !== null) normalizedUnborn++;
    affiliation194 = null;
  }
  if (affiliation194 !== null && !FACTION_IDS.has(affiliation194)) {
    errors.push(`${id} ${name}：affiliation194「${affiliation194}」不在 scenario-194.json 的 factionId 中`);
  }
  if (affiliation194 === "wuzhu") {
    errors.push(`${id} ${name}：wuzhu 是「无主之郡」的占位势力，不可作为人物归属，在野请用 null`);
  }

  officers.push({
    id,
    name,
    courtesyName: blank(courtesyRaw),
    birthYear: birthYear ?? null,
    deathYear: deathYear ?? null,
    origin: blank(originRaw),
    commandery,
    affiliation194,
    roles,
    sources,
    historicalNote: note,
    fictional,
    certainty,
    prominence,
  });
}

