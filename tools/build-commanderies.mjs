const raw = JSON.parse(fs.readFileSync("lib/game/data/commanderies-raw.json", "utf8"));
const missing = raw.filter((r) => !GEO[r.name]).map((r) => r.name);
if (missing.length) { console.error("缺坐标:", missing.join(" ")); process.exit(1); }
const extra = Object.keys(GEO).filter((k) => !raw.some((r) => r.name === k));
if (extra.length) { console.error("坐标表多余条目:", extra.join(" ")); process.exit(1); }

const pinyin = (n) => n; // 保留中文 id，避免转写歧义
const out = raw.map((r) => {
  const [seat, modern, lon, lat, certainty] = GEO[r.name];
  const fixed = SEAT_FIX[r.name];
  return {
    id: r.name,
    zhou: r.zhou,
    name: r.name,
    seat: fixed ?? r.seat,
    seatFromText: r.seat,
    seatCorrected: Boolean(fixed),
    modernReference: modern,
    longitude: lon,
    latitude: lat,
    certainty,
    counties: r.counties,
    households: r.households,
    population: r.population,
  };
});

// 校验
const bad = out.filter((c) => c.seat !== GEO[c.name][0]);
if (bad.length) { console.error("郡治与坐标表不一致:", bad.map((c) => `${c.name}:${c.seat}≠${GEO[c.name][0]}`).join(" ")); process.exit(1); }
const oob = out.filter((c) => c.longitude < 90 || c.longitude > 130 || c.latitude < 15 || c.latitude > 45);
if (oob.length) console.warn("坐标超出常规范围（请复核）:", oob.map((c) => c.name).join(" "));

fs.writeFileSync("lib/game/data/commanderies.json", JSON.stringify(out, null, 1));

const byZhou = {};
for (const c of out) byZhou[c.zhou] = (byZhou[c.zhou] ?? 0) + 1;
console.log(`✓ ${out.length} 郡国，全部带坐标`);
console.log("  " + Object.entries(byZhou).map(([z, n]) => `${z}${n}`).join(" "));
console.log(`  郡治修正 ${out.filter((c) => c.seatCorrected).length} 处：${out.filter((c) => c.seatCorrected).map((c) => `${c.name}(${c.seatFromText}→${c.seat})`).join(" ")}`);
const cert = {};
for (const c of out) cert[c.certainty] = (cert[c.certainty] ?? 0) + 1;
console.log("  位置可信度：" + Object.entries(cert).map(([k, v]) => `${k} ${v}`).join(" / "));
const lons = out.map((c) => c.longitude), lats = out.map((c) => c.latitude);
console.log(`  经度 ${Math.min(...lons)}–${Math.max(...lons)}  纬度 ${Math.min(...lats)}–${Math.max(...lats)}`);
